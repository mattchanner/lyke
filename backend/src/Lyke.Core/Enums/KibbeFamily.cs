namespace Lyke.Core.Enums;

/// <summary>
/// The five Kibbe body type families representing different Yin/Yang balances.
/// </summary>
public enum KibbeFamily
{
    /// <summary>Pure Yang - Sharp angles, elongated vertical line, chiselled features</summary>
    Dramatic = 0,

    /// <summary>Blended Yang - Blunt angularity, athletic breadth, relaxed and organic</summary>
    Natural = 1,

    /// <summary>Balanced - Perfect symmetry, even proportions, moderate in all things</summary>
    Classic = 2,

    /// <summary>Mixed Yang+Yin - Compact with high contrast, angular structure softened by rounded details</summary>
    Gamine = 3,

    /// <summary>Pure Yin - Soft curves, lush and delicate, petite with full proportions</summary>
    Romantic = 4,
}
